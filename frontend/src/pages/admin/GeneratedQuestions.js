import React, { useEffect, useMemo, useState } from 'react';
import { motion } from 'framer-motion';
import { useSearchParams, Link } from 'react-router-dom';
import { ListChecks, RefreshCcw, ArrowRightCircle } from 'lucide-react';

const apiBase = (process.env.REACT_APP_API_URL || 'http://localhost:8001').replace(/\/$/, '');
const apiRoot = `${apiBase}/api`;

const GeneratedQuestions = () => {
  const [searchParams, setSearchParams] = useSearchParams();
  const [sessions, setSessions] = useState([]);
  const [selectedSessionId, setSelectedSessionId] = useState(searchParams.get('session') || '');
  const [sessionDetails, setSessionDetails] = useState(null);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState('');

  const loadSessions = async () => {
    try {
      const response = await fetch(`${apiRoot}/interview/sessions?limit=30`);
      const data = await response.json();
      if (!response.ok) {
        throw new Error(data.detail || 'Unable to load sessions.');
      }
      const fetchedSessions = data.sessions || [];
      setSessions(fetchedSessions);

      const querySession = searchParams.get('session');
      if (querySession) {
        setSelectedSessionId(querySession);
      } else if (!selectedSessionId && fetchedSessions.length) {
        const fallbackId = fetchedSessions[0].id;
        setSelectedSessionId(fallbackId);
        setSearchParams({ session: fallbackId });
      }
    } catch (err) {
      setError(err.message || 'Failed to fetch sessions.');
    }
  };

  useEffect(() => {
    loadSessions();
  }, []);

  useEffect(() => {
    const loadSessionDetails = async () => {
      if (!selectedSessionId) {
        return;
      }
      try {
        setError('');
        setIsLoading(true);
        const response = await fetch(`${apiRoot}/interview/session/${selectedSessionId}`);
        const data = await response.json();
        if (!response.ok) {
          throw new Error(data.detail || 'Unable to load session details.');
        }
        setSessionDetails(data);
      } catch (err) {
        setError(err.message || 'Failed to fetch generated questions.');
      } finally {
        setIsLoading(false);
      }
    };

    loadSessionDetails();
  }, [selectedSessionId]);

  const questions = useMemo(() => sessionDetails?.questions || [], [sessionDetails]);

  return (
    <div className="space-y-6" data-testid="generated-questions-page">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-4xl font-bold text-white mb-2" style={{ fontFamily: 'Bebas Neue' }}>
            Generated Questions
          </h1>
          <p className="text-gray-400">View every question generated by the interviewer agent for each session.</p>
        </div>
        <Link to="/admin/create-session" className="px-4 py-2 rounded-xl text-white bg-gradient-to-r from-purple-600 to-blue-500 font-bold">
          New Session
        </Link>
      </div>

      <motion.div
        initial={{ opacity: 0, y: 15 }}
        animate={{ opacity: 1, y: 0 }}
        className="bg-gray-800/50 backdrop-blur-xl border border-gray-700 rounded-2xl p-6"
      >
        <label className="text-gray-300 text-sm font-bold uppercase tracking-wide">Choose Session</label>
        <div className="mt-3 flex items-center gap-3">
          <select
            value={selectedSessionId}
            onChange={(e) => {
              setSelectedSessionId(e.target.value);
              setSearchParams({ session: e.target.value });
            }}
            className="w-full px-4 py-3 bg-gray-900/50 border border-gray-700 rounded-xl text-white focus:border-purple-500 focus:ring-2 focus:ring-purple-500/20 outline-none"
          >
            {sessions.map((session) => (
              <option key={session.id} value={session.id}>
                {session.candidate_name || 'Unnamed'} - {session.context?.role || 'Unknown Role'} - {session.id}
              </option>
            ))}
          </select>
          <button
            type="button"
            onClick={loadSessions}
            className="p-3 rounded-xl border border-gray-700 text-gray-300 hover:border-purple-500"
            title="Refresh"
          >
            <RefreshCcw className="w-5 h-5" />
          </button>
        </div>
      </motion.div>

      {error ? <p className="text-red-400 font-medium">{error}</p> : null}

      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        className="bg-gray-800/50 backdrop-blur-xl border border-gray-700 rounded-2xl p-6"
      >
        <div className="flex items-center justify-between mb-4">
          <h2 className="text-2xl font-bold text-white" style={{ fontFamily: 'Bebas Neue' }}>
            Agent Output
          </h2>
          <span className="text-sm text-gray-400">Total Questions: {questions.length}</span>
        </div>

        {isLoading ? <p className="text-gray-300">Loading questions...</p> : null}

        {!isLoading && !questions.length ? (
          <div className="text-gray-300 border border-dashed border-gray-700 rounded-xl p-6">
            <p>No generated questions yet for this session.</p>
            <p className="mt-2 text-gray-400">Generate from Create Session or run interview question calls to populate this view.</p>
          </div>
        ) : null}

        {!isLoading && questions.length ? (
          <div className="space-y-4">
            {questions.map((question, index) => (
              <div key={question.id || `${index}-${question.question}`} className="p-4 rounded-xl border border-gray-700 bg-gray-900/50">
                <div className="flex flex-wrap items-center gap-2 mb-3">
                  <span className="text-xs uppercase tracking-wide px-2 py-1 rounded bg-indigo-500/20 text-indigo-300 border border-indigo-500/40">
                    {question.type || 'technical'}
                  </span>
                  <span className="text-xs uppercase tracking-wide px-2 py-1 rounded bg-orange-500/20 text-orange-300 border border-orange-500/40">
                    {question.difficulty || 'medium'}
                  </span>
                  <span className="text-xs uppercase tracking-wide px-2 py-1 rounded bg-emerald-500/20 text-emerald-300 border border-emerald-500/40">
                    {question.company_type || sessionDetails?.context?.company_type || 'startup'}
                  </span>
                  <span className="text-xs uppercase tracking-wide px-2 py-1 rounded bg-slate-500/20 text-slate-300 border border-slate-500/40">
                    {question.generation_source || 'strands_tools'}
                  </span>
                </div>
                <p className="text-white leading-relaxed">{index + 1}. {question.question}</p>
                {question.generated_at ? <p className="mt-2 text-xs text-gray-400">Generated: {question.generated_at}</p> : null}
              </div>
            ))}
          </div>
        ) : null}
      </motion.div>

      {sessionDetails?.id ? (
        <div className="flex items-center gap-4 text-sm text-gray-300">
          <span className="inline-flex items-center gap-2"><ListChecks className="w-4 h-4" /> Session ID: {sessionDetails.id}</span>
          <Link to={`/admin/results?session=${encodeURIComponent(sessionDetails.id)}`} className="inline-flex items-center gap-2 text-purple-300 hover:text-purple-200">
            Open Results <ArrowRightCircle className="w-4 h-4" />
          </Link>
        </div>
      ) : null}
    </div>
  );
};

export default GeneratedQuestions;
